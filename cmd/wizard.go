package cmd

import (
	"bufio"
	"fmt"
	"io"
	"net"
	"strings"

	"github.com/fsuhrau/automationhub/config"
	"github.com/fsuhrau/automationhub/device/androiddevice"
	"github.com/fsuhrau/automationhub/device/iosdevice"
	"github.com/fsuhrau/automationhub/device/iossim"
	"github.com/fsuhrau/automationhub/device/unityeditor"
)

const (
	rule        = "------------------------------------"
	yesNoSuffix = " (y/n)"
	screenshotQ = "Capture Native Screenshots?" + yesNoSuffix
	iosBundleID = "com.automationhub.integration"
)

var screenshotInfo = []string{ //nolint:gochecknoglobals // constant prompt text
	"There are two different ways to create screenshots in case of test failures",
	"Native Screenshots are generated by OS and can capture OS Dialogs as well but be careful because it can expose sensitive parts-",
	"Simulated Screenshots are generated in app and can't capture external dialogs which makes it more difficult to see whats broken.",
	"",
}

// wizard asks questions on out and reads the answers from in. The first
// failing read or write is kept in err and stops all later questions.
type wizard struct {
	in  *bufio.Reader
	out io.Writer
	err error
}

func newWizard(in io.Reader, out io.Writer) *wizard {
	return &wizard{in: bufio.NewReader(in), out: out}
}

func (w *wizard) write(s string) {
	if w.err != nil {
		return
	}
	if _, err := io.WriteString(w.out, s); err != nil {
		w.err = fmt.Errorf("write output: %w", err)
	}
}

func (w *wizard) say(lines ...string) {
	for _, l := range lines {
		w.write(l + "\n")
	}
}

func (w *wizard) readLine(prompt string) string {
	if w.err != nil {
		return ""
	}
	w.write(prompt + " -> ")
	line, err := w.in.ReadString('\n')
	if err != nil && line == "" && w.err == nil {
		w.err = fmt.Errorf("read input: %w", err)
	}
	return strings.TrimSpace(line)
}

// choose asks until the answer is one of valid.
func (w *wizard) choose(prompt string, valid ...string) string {
	for w.err == nil {
		answer := w.readLine(prompt)
		for _, v := range valid {
			if v == answer {
				return answer
			}
		}
	}
	return ""
}

func (w *wizard) askYes(prompt string) bool {
	return w.choose(prompt+yesNoSuffix, "y", "n") == "y"
}

func (w *wizard) readIP(prompt string) string {
	for w.err == nil {
		if answer := w.readLine(prompt); net.ParseIP(answer) != nil {
			return answer
		}
	}
	return ""
}

// collect runs the whole wizard.
func (w *wizard) collect() (config.Service, error) {
	cfg := config.Service{DeviceManager: make(map[string]config.Manager)}
	w.say("Welcome to the configuration wizard.", "you can cancel the wizard any time by Ctrl+C", rule, "")
	w.askHostIP(&cfg)
	w.say(rule, "The hub is able to manage different devices like android, ios, ...",
		"you can enable / disable managers dependent on your needs.", "")
	for _, p := range managerPrompts() {
		w.askManager(&cfg, p)
	}
	return cfg, w.err
}

func (w *wizard) askHostIP(cfg *config.Service) {
	w.say("Basic Service Setup", "-------------------",
		"To run tests each device needs to know which ip to connect to.",
		"This hub is able to auto detect an external ip on startup or you can set a fixed one.", "")
	cfg.Autodetect = w.askYes("Auto detect service ip on startup?")
	w.say("")
	if !cfg.Autodetect {
		cfg.HostIP = w.readIP("Set static ip. (format: 0.0.0.0)")
	}
}

type managerPrompt struct {
	name        string
	question    string
	preface     []string
	screenshots bool
	webDriver   bool
}

func managerPrompts() []managerPrompt {
	return []managerPrompt{
		{name: androiddevice.Manager, question: "Enable Android Device Manager?", screenshots: true},
		{name: iosdevice.Manager, question: "Enable iOS Device Manager (real devices)?", screenshots: true, webDriver: true},
		{name: iossim.Manager, question: "Enable iOS Simulator Manager?", screenshots: true},
		{
			name:     unityeditor.Manager,
			question: "Enable Unity Editor Manager?",
			preface: []string{
				"Unity Editor can be managed as well which can be used to execute PlayMode in a 'swarm' mode and create similar reports like on device.",
				"",
			},
		},
	}
}

func (w *wizard) askManager(cfg *config.Service, p managerPrompt) {
	w.say(p.preface...)
	if !w.askYes(p.question) {
		w.say("")
		return
	}
	m := config.Manager{Enabled: true}
	if p.webDriver {
		m.WebDriver = &config.WebDriver{BundleID: iosBundleID}
	}
	if p.screenshots {
		w.say("")
		w.say(screenshotInfo...)
		m.UseOSScreenshot = w.choose(screenshotQ, "y", "n") == "y"
	}
	w.say("")
	cfg.DeviceManager[p.name] = m
}
